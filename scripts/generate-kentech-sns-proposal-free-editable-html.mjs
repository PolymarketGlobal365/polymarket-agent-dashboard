function esc(text) {
  return String(text ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function page(title, subtitle, blocks, pageNo) {
  return `
  <section class="page">
    <div class="page-no">${esc(pageNo)}</div>
    <h1>${esc(title)}</h1>
    ${subtitle ? `<p class="subtitle">${esc(subtitle)}</p>` : ""}
    ${blocks.join("")}
  </section>
  `;
}

function sectionPage(part, title, summary, pageNo) {
  return `
  <section class="page section-page">
    <div class="page-no">${esc(pageNo)}</div>
    <div class="part">${esc(part)}</div>
    <div class="section-no">${esc(pageNo)}</div>
    <h1>${esc(title)}</h1>
    <p class="summary">${esc(summary)}</p>
  </section>
  `;
}

function p(text) {
  return `<p>${esc(text)}</p>`;
}

function bullets(items) {
  return `<ul>${items.map((item) => `<li>${esc(item)}</li>`).join("")}</ul>`;
}

function note(text) {
  return `<div class="note">${esc(text)}</div>`;
}

function table(headers, rows) {
  return `
  <table>
    <thead>
      <tr>${headers.map((h) => `<th>${esc(h)}</th>`).join("")}</tr>
    </thead>
    <tbody>
      ${rows.map((row) => `<tr>${row.map((cell) => `<td>${esc(cell)}</td>`).join("")}</tr>`).join("")}
    </tbody>
  </table>`;
}

