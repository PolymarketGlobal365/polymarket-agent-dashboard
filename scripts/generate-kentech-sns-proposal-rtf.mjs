function rtfEscape(text) {
  let out = "";
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === "{") out += "\\{";
    else if (ch === "}") out += "\\}";
    else if (ch === "\n") out += "\\line ";
    else if (code <= 0x7f) out += ch;
    else {
      const signed = code > 32767 ? code - 65536 : code;
      out += `\\u${signed}?`;
    }
  }
  return out;
}

function para(text, opts = {}) {
  const align = opts.align === "center" ? "\\qc" : opts.align === "right" ? "\\qr" : "\\ql";
  const size = opts.size ?? 20;
  const bold = opts.bold ? "\\b" : "";
  const italic = opts.italic ? "\\i" : "";
  const spaceBefore = opts.spaceBefore ?? 0;
  const spaceAfter = opts.spaceAfter ?? 120;
  return `{\\pard${align}\\sa${spaceAfter}\\sb${spaceBefore}\\sl300\\slmult1${bold}${italic}\\fs${size} ${rtfEscape(text)}\\par}\n`;
}

function bullet(text, level = 0) {
  const left = 520 + level * 260;
  const indent = 220;
  return `{\\pard\\ql\\li${left}\\fi-${indent}\\sa90\\sl280\\slmult1\\fs20 - ${rtfEscape(text)}\\par}\n`;
}

function smallGap() {
  return para("", { spaceAfter: 80 });
}

function pageBreak() {
  return "\\page\n";
}

